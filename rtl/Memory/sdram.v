`timescale 1ns/1ps

`include "sdram_pkg.vh"

module sdram_fsm(

    //------------------------------------------------------------
    // Clock / Reset
    //------------------------------------------------------------

    input wire clk,
    input wire rst,


    //------------------------------------------------------------
    // Control Inputs
    //------------------------------------------------------------

    input wire start_read,
    input wire start_write,

    input wire refresh_request,

    input wire timer_done,

    //------------------------------------------------------------
    // Saved Operation Type
    //------------------------------------------------------------
    // This is important.
    //
    // start_read/start_write are request pulses.
    // They may be LOW by the time SDRAM reaches ACTIVATE.
    //
    // op_is_read is generated by sdram_controller from the
    // saved request and therefore remains valid throughout
    // the transaction.
    //------------------------------------------------------------

    input wire op_is_read,


    //------------------------------------------------------------
    // State Outputs
    //------------------------------------------------------------

    output reg [3:0] state,
    output reg [3:0] next_state

);


//============================================================
// STATE REGISTER
//============================================================

always @(posedge clk or posedge rst)
begin

    if (rst)

        state <= `SDRAM_RESET;

    else

        state <= next_state;

end


//============================================================
// NEXT STATE LOGIC
//============================================================

always @(*)
begin

    //--------------------------------------------------------
    // Default
    //--------------------------------------------------------

    next_state = state;


    case(state)


        //====================================================
        // RESET
        //====================================================

        `SDRAM_RESET:
        begin

            if(timer_done)

                next_state = `SDRAM_PRECHARGE;

        end


        //====================================================
        // INITIAL PRECHARGE
        //====================================================

        `SDRAM_PRECHARGE:
        begin

            if(timer_done)

                next_state = `SDRAM_REFRESH1;

        end


        //====================================================
        // REFRESH #1
        //====================================================

        `SDRAM_REFRESH1:
        begin

            if(timer_done)

                next_state = `SDRAM_REFRESH2;

        end


        //====================================================
        // REFRESH #2
        //====================================================

        `SDRAM_REFRESH2:
        begin

            if(timer_done)

                next_state = `SDRAM_MODE;

        end


        //====================================================
        // MODE REGISTER
        //====================================================

        `SDRAM_MODE:
        begin

            if(timer_done)

                next_state = `SDRAM_IDLE;

        end


        //====================================================
        // IDLE
        //====================================================

        `SDRAM_IDLE:
        begin

            //------------------------------------------------
            // Refresh has highest priority
            //------------------------------------------------

            if(refresh_request)

                next_state = `SDRAM_REFRESH1;


            //------------------------------------------------
            // New READ transaction
            //------------------------------------------------

            else if(start_read)

                next_state = `SDRAM_ACTIVATE;


            //------------------------------------------------
            // New WRITE transaction
            //------------------------------------------------

            else if(start_write)

                next_state = `SDRAM_ACTIVATE;

        end


        //====================================================
        // ACTIVATE
        //====================================================
        //
        // IMPORTANT FIX:
        //
        // DO NOT use start_read here.
        //
        // start_read is only the original request signal.
        // By the time ACTIVATE completes, start_read can
        // already be LOW.
        //
        // op_is_read comes from the saved transaction in
        // sdram_controller and remains valid.
        //
        //====================================================

        `SDRAM_ACTIVATE:
        begin

            if(timer_done)
            begin

                //------------------------------------------------
                // Saved transaction was READ
                //------------------------------------------------

                if(op_is_read)

                    next_state = `SDRAM_READ;


                //------------------------------------------------
                // Saved transaction was WRITE
                //------------------------------------------------

                else

                    next_state = `SDRAM_WRITE;

            end

        end


        //====================================================
        // READ
        //====================================================

        `SDRAM_READ:
        begin

            if(timer_done)

                next_state = `SDRAM_PRECHARGE_ROW;

        end


        //====================================================
        // WRITE
        //====================================================

        `SDRAM_WRITE:
        begin

            if(timer_done)

                next_state = `SDRAM_PRECHARGE_ROW;

        end


        //====================================================
        // PRECHARGE AFTER READ / WRITE
        //====================================================

        `SDRAM_PRECHARGE_ROW:
        begin

            if(timer_done)

                next_state = `SDRAM_IDLE;

        end


        //====================================================
        // WAIT
        //====================================================

        `SDRAM_WAIT:
        begin

            if(timer_done)

                next_state = `SDRAM_IDLE;

        end


        //====================================================
        // DEFAULT
        //====================================================

        default:
        begin

            next_state = `SDRAM_RESET;

        end


    endcase

end


endmodule

`include "sdram_pkg.vh"

module refresh_controller(

    //------------------------------------------------------------
    // Clock / Reset
    //------------------------------------------------------------

    input wire clk,
    input wire rst,

    //------------------------------------------------------------
    // Refresh Acknowledge
    //------------------------------------------------------------

    input wire refresh_done,

    //------------------------------------------------------------
    // Refresh Request
    //------------------------------------------------------------

    output reg refresh_request

);

    //------------------------------------------------------------
    // Refresh Counter
    //------------------------------------------------------------

    reg [15:0] refresh_counter;

    //------------------------------------------------------------
    // Counter Logic
    //------------------------------------------------------------

    always @(posedge clk or posedge rst)
    begin

        if(rst)
        begin

            refresh_counter <= 16'd0;

            refresh_request <= 1'b0;

        end

        else
        begin

            //----------------------------------------------------
            // Waiting for Refresh Interval
            //----------------------------------------------------

            if(refresh_counter == (`REFRESH_PERIOD-1))
            begin

                refresh_counter <= 16'd0;

                refresh_request <= 1'b1;

            end

            //----------------------------------------------------
            // Counting
            //----------------------------------------------------

            else
            begin

                refresh_counter <= refresh_counter + 16'd1;

            end

            //----------------------------------------------------
            // Refresh Completed
            //----------------------------------------------------

            if(refresh_done)

                refresh_request <= 1'b0;

        end

    end

endmodule

