wire refresh_done;

wire [3:0] state;
wire [3:0] next_state;

wire timer_done;
wire op_is_read;

//------------------------------------------------------------
// SDRAM Physical Interface (internal only -- no longer external
// ports, since sdram_model is now instantiated right here)
