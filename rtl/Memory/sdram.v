module sdram_top(

    //------------------------------------------------------------
    // Clock / Reset
    //------------------------------------------------------------

    input wire clk,
    input wire rst,

    //------------------------------------------------------------
    // CPU Interface
    //------------------------------------------------------------
    // This is now the ENTIRE external interface of sdram_top. The
    // physical SDRAM pins (cs_n/ras_n/cas_n/we_n/sdram_addr/bank_addr/
    // dq_out/dq_in/dq_oe) used to be ports here too -- which was the
    // actual bug: they were commands going nowhere, because nothing
    // outside sdram_top ever connected them to a memory device.
    // sdram_model is instantiated below instead, so those signals are
    // now purely internal.

    input wire read_req,
    input wire write_req,

    input wire [31:0] address,
    input wire [31:0] write_data,

    output wire [31:0] read_data,

    output wire ready

);

