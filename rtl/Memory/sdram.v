module sdram_model(

    //------------------------------------------------------------
    // Clock
    //------------------------------------------------------------

    input wire clk,

    //------------------------------------------------------------
    // SDRAM Commands
    //------------------------------------------------------------

    input wire cs_n,
    input wire ras_n,
    input wire cas_n,
    input wire we_n,

    //------------------------------------------------------------
    // Address
    //------------------------------------------------------------

    input wire [12:0] addr,

    input wire [1:0] bank,

    //------------------------------------------------------------
    // Data Bus
    //------------------------------------------------------------

    input wire [15:0] dq_in,

    output reg [15:0] dq_out,

    input wire dq_oe

);
  
//------------------------------------------------------------
// SDRAM Memory
//
// 4 Banks × 8192 Rows × 512 Columns
//------------------------------------------------------------

localparam SDRAM_DEPTH =
    `SDRAM_BANKS *
    `SDRAM_ROWS *
    `SDRAM_COLUMNS;

reg [15:0] memory [0:SDRAM_DEPTH-1];

//------------------------------------------------------------
// Physical SDRAM Address
//------------------------------------------------------------

wire [23:0] memory_index;

assign memory_index =
    {
        active_bank,
        active_row,
        addr[8:0]
    };
  
//------------------------------------------------------------
// Active Row
//------------------------------------------------------------

reg [12:0] active_row;
reg [1:0] active_bank;  
reg row_open;
//------------------------------------------------------------
// Initialize
//------------------------------------------------------------

integer i;

initial
begin

    row_open = 1'b0;

    dq_out = 16'd0;

    for(i = 0; i < SDRAM_DEPTH; i = i + 1)

        memory[i]=16'd0;

end
//------------------------------------------------------------
// Command Decode
//------------------------------------------------------------

always @(posedge clk)
begin

    if(!cs_n)
    begin

        //------------------------------------------
        // ACTIVE
        //------------------------------------------

if(!ras_n && cas_n && we_n)
begin

    active_row  <= addr;
    active_bank <= bank;

    row_open <= 1'b1;

end
        //------------------------------------------
        // READ
        //------------------------------------------

        else if(ras_n && !cas_n && we_n)
        begin

            if(row_open)

                dq_out <= memory[memory_index];

        end

        //------------------------------------------
        // WRITE
        //------------------------------------------

        else if(ras_n && !cas_n && !we_n)
        begin

            if(row_open && dq_oe)

                memory[memory_index] <= dq_in;

        end

        //------------------------------------------
        // PRECHARGE
        //------------------------------------------

        else if(!ras_n && cas_n && !we_n)
        begin

            row_open <= 1'b0;

        end

    end

end
endmodule